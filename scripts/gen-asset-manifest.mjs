// Scans public/assets/themes for REAL images (anything NOT named *_PLACEHOLDER.*) and writes themes/assets.generated.js.
// Runs automatically before `npm run dev` and `npm run build`. Drop an image in, restart, done.
import fs from "node:fs";
import path from "node:path";

const root = "public/assets/themes";
const out = {};
for (const theme of fs.existsSync(root) ? fs.readdirSync(root) : []) {
  const dir = path.join(root, theme);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const file of fs.readdirSync(dir)) {
    if (/_PLACEHOLDER\./i.test(file)) continue;
    const m = file.match(/^(.+?)_(background|icon|hero)\.(png|jpe?g|webp|svg)$/i);
    if (m && m[1] === theme) (out[theme] ??= {})[m[2].toLowerCase()] = `/assets/themes/${theme}/${file}`;
  }
}
fs.writeFileSync("themes/assets.generated.js", `// AUTO-GENERATED by scripts/gen-asset-manifest.mjs - do not edit.\nexport const INSTALLED_ASSETS = ${JSON.stringify(out, null, 2)};\n`);
console.log(`Theme assets installed: ${Object.keys(out).length ? JSON.stringify(out) : "none (placeholders only - app works without them)"}`);
